ASSISTANT_NOTICE = "Generated by the local model. This is not an official academic result."


def student_or_404(db: Session, student_id: int) -> Student:
    student = db.get(Student, student_id)
    if student is None:
        raise HTTPException(status_code=404, detail=f"No student found with id {student_id}.")
    return student


def subject_or_404(db: Session, subject_id: int) -> Subject:
    subject = db.get(Subject, subject_id)
    if subject is None:
        raise HTTPException(status_code=404, detail=f"No subject found with id {subject_id}.")
    return subject


def require_active_subject(db: Session, subject_id: int) -> Subject:
    """Reject a missing or inactive subject for a new concern, resource, or assessment."""
    subject = subject_or_404(db, subject_id)
    if not subject.is_active:
        raise HTTPException(
            status_code=422,
            detail="Choose an active subject. An inactive subject stays on historical records and cannot be used for a new concern or assessment.",
        )
    return subject


def write_audit(db: Session, actor: User | None, action: str, entity_type: str, entity_id: int | str, detail: str) -> None:
    """Record an administrative change in the same transaction as the change."""
    db.add(
        AuditLog(
            actor_user_id=None if actor is None else actor.id,
            action=action,
            entity_type=entity_type,
            entity_id=str(entity_id),
            detail=detail[:500],
            created_at=datetime.now(timezone.utc),
        )
    )


def feedback_payload(item: Feedback) -> dict:
    """Shape one feedback row and label it as student-reported."""
    return {
        "id": item.id,
        "student_id": item.student_id,
        "subject_id": item.subject_id,
        "subject_name": item.subject.name if item.subject is not None else None,
        "topic": item.topic,
        "difficult_topics": item.difficult_topics,
        "explanation_request": item.explanation_request,
        "practice_request": item.practice_request,
        "preferred_format": item.preferred_format,
        "resource_note": item.resource_note,
        "resource_rating": item.resource_rating,
        "created_at": item.created_at,
        "reported_by_student": True,
    }


