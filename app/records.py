def stored_feedback(db: Session, student_id: int) -> list[dict]:
    statement = (
        select(Feedback)
        .options(joinedload(Feedback.subject))
        .where(Feedback.student_id == student_id)
        .order_by(Feedback.created_at, Feedback.id)
    )
    return [feedback_payload(item) for item in db.scalars(statement).unique().all()]


def stored_resources(db: Session) -> list[dict]:
    statement = (
        select(LearningResource)
        .options(joinedload(LearningResource.subject))
        .order_by(LearningResource.title)
    )
    return [resource_payload(resource) for resource in db.scalars(statement).unique().all()]


def concern_rows_as_feedback(concerns: list[Concern]) -> list[dict]:
    """Let the study outline see concerns without treating them as official marks."""
    rows = []
    for concern in concerns:
        rows.append(
            {
                "subject_id": concern.subject_id,
                "subject_name": concern.subject.name if concern.subject is not None else None,
                "topic": concern.topic,
                "difficult_topics": concern.description,
                "explanation_request": concern.concept,
                "practice_request": None,
                "preferred_format": concern.preferred_format,
                "resource_note": None,
                "resource_rating": None,
            }
        )
    return rows


def _assistant_resources(
    catalog: list[dict],
    results: list[dict],
    concerns: list[Concern],
    active_ids: set[int],
) -> list[dict]:
    """Stored resources for active subjects that need support or were reported."""
    selected = [
        resource for resource in select_resources(catalog, results) if resource["subject_id"] in active_ids
    ]
    seen = {item["id"] for item in selected}
    concern_subjects = {item.subject_id for item in concerns if item.subject_id in active_ids}
    for resource in catalog:
        if resource["subject_id"] in concern_subjects and resource["id"] not in seen:
            selected.append(resource)
            seen.add(resource["id"])
    selected.sort(key=lambda resource: (resource["subject_name"] or "", resource["title"]))
    return selected


def assistant_bundle(db: Session, student_id: int) -> dict:
    """Load one student and the small set of facts the model is allowed to see."""
    student = student_or_404(db, student_id)
    results = results_for_student(db, student_id)
    report = academic_report(db, student_id)
    official = report["subjects"]
    active_ids = {row.id for row in ordered_active_subjects(db)}
    feedback = [
        row for row in stored_feedback(db, student_id)
        if row.get("subject_id") is None or row.get("subject_id") in active_ids
    ]
    concerns = [
        concern for concern in db.scalars(
            select(Concern).options(joinedload(Concern.subject)).where(Concern.student_id == student_id)
        ).unique().all()
        if concern.subject_id in active_ids
    ]
    feedback = feedback + concern_rows_as_feedback(list(concerns))
    resources = _assistant_resources(stored_resources(db), official, concerns, active_ids)
    outline = build_study_outline(official, feedback)
    aggregate = aggregate_percentage(results)
    attendance = attendance_report(db, student_id)
    facts = build_facts(
        {"full_name": student.full_name, "admission_number": student.admission_number},
        official,
        feedback,
        resources,
        outline,
        attendance={
            "sessions": attendance["summary"]["sessions"],
            "attended": attendance["summary"]["attended"],
            "absent": attendance["summary"]["absent"],
            "percentage": attendance["summary"]["percentage"],
            "by_subject": [
                {
                    "subject": row["subject_name"],
                    "attended": row["attended"],
                    "sessions": row["total"],
                    "percentage": row["percentage"],
                }
                for row in attendance["by_subject"]
                if row["subject_id"] in active_ids
            ],
        },
    )
    facts["academic_rules"] = {
        "department": DEPARTMENT,
        "semester": SEMESTER,
        "active_subjects": [row["subject_name"] for row in official],
        "rounding_rule": report["rounding_rule"],
    }
    facts["concerns"] = [
        {
            "subject": item.subject.name if item.subject is not None else None,
            "topic": item.topic,
            "description": item.description,
            "concept": item.concept,
            "assistance_requested": item.assistance_type,
            "status": item.status,
            "meaning": "Reported by the student. Not a verified academic fact.",
        }
        for item in concerns
    ]
    return {
        "student": student,
        "results": results,
        "aggregate": aggregate,
        "academic_report": report,
        "resources": resources,
        "outline": outline,
        "facts": facts,
    }


def assistant_answer(task: str, facts: dict, question: str | None = None) -> dict:
    """Ask Ollama to explain facts. Failure here does not change stored marks."""
    try:
        prompt = build_prompt(task, facts, question)
        narrative = generate_text(prompt)
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from None
    except AssistantUnavailable as exc:
        raise HTTPException(status_code=503, detail=exc.detail) from None
    return {
        "notice": ASSISTANT_NOTICE,
        "model": model_name(),
        "narrative": narrative,
        "facts": facts,
    }


def attendance_report(db: Session, student_id: int) -> dict:
    """Count attendance and calculate percentages in Python."""
    rows = db.scalars(
        select(AttendanceRecord)
        .options(joinedload(AttendanceRecord.subject))
        .where(AttendanceRecord.student_id == student_id)
        .order_by(AttendanceRecord.session_date, AttendanceRecord.id)
    ).unique().all()
    records = []
    by_subject: dict[int, dict] = {}
    attended = 0
    for row in rows:
        if row.status == "present":
            attended += 1
        subject_name = row.subject.name if row.subject is not None else ""
        records.append(
            {
                "id": row.id,
                "student_id": row.student_id,
                "subject_id": row.subject_id,
                "subject_name": subject_name,
                "session_date": row.session_date,
                "status": row.status,
            }
        )
        bucket = by_subject.setdefault(
            row.subject_id,
            {"subject_id": row.subject_id, "subject_name": subject_name, "attended": 0, "total": 0},
        )
        bucket["total"] += 1
        if row.status == "present":
            bucket["attended"] += 1

    subjects = []
    for bucket in by_subject.values():
        percent = attendance_percentage(bucket["attended"], bucket["total"])
        subjects.append(
            {
                **bucket,
                "percentage": None if percent is None else format(percent, "f"),
            }
        )
    subjects.sort(key=lambda item: item["subject_name"])
    overall = attendance_percentage(attended, len(records))
    return {
        "records": records,
        "summary": {
            "sessions": len(records),
            "attended": attended,
            "absent": len(records) - attended,
            "percentage": None if overall is None else format(overall, "f"),
        },
        "by_subject": subjects,
    }


def save_study_plan(db: Session, student_id: int, outline: dict) -> StudyPlan:
    """Store the rule-based outline so it is not only kept in the browser."""
    plan = StudyPlan(
        student_id=student_id,
        source=str(outline.get("source") or "academic_rules"),
        outline_text=json.dumps(outline),
        created_at=datetime.now(timezone.utc),
    )
    db.add(plan)
    return plan


def latest_study_plan(db: Session, student_id: int) -> dict | None:
    plan = db.scalar(
        select(StudyPlan).where(StudyPlan.student_id == student_id).order_by(StudyPlan.id.desc()).limit(1)
    )
    if plan is None:
        return None
    try:
        outline = json.loads(plan.outline_text)
    except ValueError:
        outline = {"source": plan.source, "items": [], "note": "The stored outline could not be read."}
    return {"id": plan.id, "created_at": plan.created_at, "outline": outline}


def concern_payload(db: Session, concern: Concern) -> dict:
    updates = db.scalars(
        select(ConcernUpdate).where(ConcernUpdate.concern_id == concern.id).order_by(ConcernUpdate.id)
    ).all()
    links = db.scalars(
        select(ConcernResource)
        .options(joinedload(ConcernResource.resource).joinedload(LearningResource.subject))
        .where(ConcernResource.concern_id == concern.id)
        .order_by(ConcernResource.id)
    ).unique().all()
    return {
        "id": concern.id,
        "student_id": concern.student_id,
        "student_name": concern.student.full_name if concern.student is not None else None,
        "admission_number": concern.student.admission_number if concern.student is not None else None,
        "subject_id": concern.subject_id,
        "subject_name": concern.subject.name if concern.subject is not None else None,
        "topic": concern.topic,
        "description": concern.description,
        "concept": concern.concept,
        "assistance_type": concern.assistance_type,
        "preferred_format": concern.preferred_format,
        "status": concern.status,
        "priority": concern.priority,
        "created_at": concern.created_at,
        "resolved_at": concern.resolved_at,
        "reported_by_student": True,
        "updates": [
            {
                "id": item.id,
                "kind": item.kind,
                "message": item.message,
                "created_at": item.created_at,
            }
            for item in updates
        ],
        "resources": [resource_payload(link.resource) for link in links if link.resource is not None],
    }


def load_concern(db: Session, concern_id: int) -> Concern:
    concern = db.scalar(
        select(Concern)
        .options(joinedload(Concern.student), joinedload(Concern.subject))
        .where(Concern.id == concern_id)
    )
    if concern is None:
        raise HTTPException(status_code=404, detail=f"No concern found with id {concern_id}.")
    return concern


def delete_student_graph(db: Session, student: Student) -> None:
    """Remove a student and the rows that belong only to that student.

    Audit history is kept. Learning resources are shared, so they stay.
    """
    concern_ids = list(db.scalars(select(Concern.id).where(Concern.student_id == student.id)).all())
    if concern_ids:
        db.execute(delete(ConcernResource).where(ConcernResource.concern_id.in_(concern_ids)))
        db.execute(delete(ConcernUpdate).where(ConcernUpdate.concern_id.in_(concern_ids)))
        db.execute(delete(Concern).where(Concern.id.in_(concern_ids)))
    db.execute(delete(AttendanceRecord).where(AttendanceRecord.student_id == student.id))
    db.execute(delete(StudyPlan).where(StudyPlan.student_id == student.id))
    db.execute(delete(Feedback).where(Feedback.student_id == student.id))
    db.execute(delete(InternalAssessment).where(InternalAssessment.student_id == student.id))
    db.execute(delete(ExternalExamination).where(ExternalExamination.student_id == student.id))
    db.execute(delete(Mark).where(Mark.student_id == student.id))
    db.execute(delete(AdminNotification).where(AdminNotification.student_id == student.id))
    user = db.scalar(select(User).where(User.student_id == student.id))
    if user is not None:
        db.execute(delete(LoginSession).where(LoginSession.user_id == user.id))
        db.delete(user)
    db.delete(student)
