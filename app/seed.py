def _align_academic_structure(session: Session, students: dict, subjects: dict) -> None:
    """Point the current programme at Semester 1 Computer Science without deleting rows."""
    for code, name in ACTIVE_SUBJECTS:
        subject = subjects.get(code)
        if subject is None:
            continue
        subject.name = name
        subject.is_active = True
    historical_codes = set(RETIRED_SUBJECT_CODES) | {"301"}
    for subject in session.scalars(select(Subject)).all():
        if subject.code in historical_codes:
            subject.is_active = False
    for student in students.values():
        student.department = DEPARTMENT
        student.year_or_semester = SEMESTER
    for url, code in RESOURCE_SUBJECT_BY_URL.items():
        subject = subjects.get(code)
        resource = session.scalar(select(LearningResource).where(LearningResource.url == url))
        if subject is not None and resource is not None:
            resource.subject_id = subject.id
    math_subject = subjects.get("MATH")
    dsa_subject = subjects.get("DSA")
    if math_subject is not None and dsa_subject is not None:
        demo_ids = [student.id for student in students.values() if student.is_demo]
        if demo_ids:
            math_rows = session.scalars(
                select(AttendanceRecord).where(
                    AttendanceRecord.subject_id == math_subject.id,
                    AttendanceRecord.student_id.in_(demo_ids),
                )
            ).all()
            for row in math_rows:
                clash = session.scalar(
                    select(AttendanceRecord.id).where(
                        AttendanceRecord.student_id == row.student_id,
                        AttendanceRecord.subject_id == dsa_subject.id,
                        AttendanceRecord.session_date == row.session_date,
                    )
                )
                if clash is None:
                    row.subject_id = dsa_subject.id
    for item in DEMO_FEEDBACK:
        existing = session.scalar(select(Feedback).where(Feedback.seed_key == item["seed_key"]))
        subject = subjects.get(item["subject_code"])
        if existing is not None and subject is not None:
            existing.subject_id = subject.id
            existing.topic = item["topic"]
            existing.difficult_topics = item["difficult_topics"]
    session.flush()


def _seed_assessments(session: Session, students: dict, subjects: dict) -> int:
    """Insert demo internal and external scores once. Later runs do not overwrite them."""
    created = 0
    for item in demo_assessments():
        student = students[item["admission_number"]]
        subject = subjects[item["subject_code"]]
        created += _insert_if_absent(
            session,
            InternalAssessment,
            {
                "student_id": student.id,
                "subject_id": subject.id,
                "cat_1": item["cat_1"],
                "assignment_1": item["assignment_1"],
                "cat_2": item["cat_2"],
                "assignment_2": item["assignment_2"],
                "cat_3": item["cat_3"],
                "assignment_3": item["assignment_3"],
            },
            ["student_id", "subject_id"],
        )
        if item["external_raw"] is not None:
            created += _insert_if_absent(
                session,
                ExternalExamination,
                {
                    "student_id": student.id,
                    "subject_id": subject.id,
                    "raw_mark": item["external_raw"],
                },
                ["student_id", "subject_id"],
            )
    return created


def _seed_concerns(session: Session, students: dict, subjects: dict) -> int:
    """Insert a concern once. A second run finds the seed key and skips it."""
    created = 0
    moment = datetime(2026, 9, 20, 10, 0, tzinfo=timezone.utc)
    for item in EXTRA_CONCERNS:
        existing = session.scalar(select(Concern).where(Concern.seed_key == item["seed_key"]))
        if existing is not None:
            subject = subjects.get(item["subject_code"])
            if subject is not None:
                existing.subject_id = subject.id
                existing.topic = item["topic"]
                existing.description = item["description"]
                existing.concept = item["concept"]
            continue
        concern = Concern(
            student_id=students[item["admission_number"]].id,
            subject_id=subjects[item["subject_code"]].id,
            topic=item["topic"],
            description=item["description"],
            concept=item["concept"],
            assistance_type=item["assistance_type"],
            preferred_format=item["preferred_format"],
            status=item["status"],
            priority=item["priority"],
            created_at=moment,
            resolved_at=moment if item["status"] in {"resolved", "closed"} else None,
            seed_key=item["seed_key"],
        )
        session.add(concern)
        session.flush()
        if item["response"]:
            session.add(
                ConcernUpdate(
                    concern_id=concern.id,
                    author_user_id=None,
                    kind="admin_response",
                    message=item["response"],
                    created_at=moment,
                )
            )
        if item["resource_url"]:
            resource = session.scalar(select(LearningResource).where(LearningResource.url == item["resource_url"]))
            if resource is not None:
                session.add(
                    ConcernResource(
                        concern_id=concern.id,
                        resource_id=resource.id,
                        recommended_by_user_id=None,
                        created_at=moment,
                    )
                )
        created += 1
    return created


def _seed_study_plans(session: Session, students: dict) -> int:
    """Store the rule-based outline once for selected demo students."""
    from app.records import assistant_bundle, save_study_plan

    created = 0
    for admission_number in STUDY_PLAN_ADMISSIONS:
        student = students[admission_number]
        already = session.scalar(
            select(StudyPlan.id).where(StudyPlan.student_id == student.id, StudyPlan.source == "demo_seed")
        )
        if already is not None:
            continue
        outline = dict(assistant_bundle(session, student.id)["outline"])
        outline["source"] = "demo_seed"
        save_study_plan(session, student.id, outline)
        created += 1
    return created


