def _unique_keys(rows: tuple[dict, ...], key_func, label: str) -> None:
    seen = set()
    for row in rows:
        key = key_func(row)
        if key in seen:
            raise ValueError(f"Demo {label} contains a duplicate {key}.")
        seen.add(key)


def validate_demo_data() -> None:
    """Reject demo rows that would break the mark rules or point at missing records."""
    all_students = DEMO_STUDENTS + EXTRA_STUDENTS
    all_marks = DEMO_MARKS + tuple(extra_marks())
    _unique_keys(all_students, lambda row: row["admission_number"], "students")
    _unique_keys(all_students, lambda row: row["email"], "student emails")
    _unique_keys(DEMO_RESOURCES, lambda row: row["url"], "resources")
    _unique_keys(DEMO_FEEDBACK, lambda row: row["seed_key"], "feedback")
    _unique_keys(DEMO_SUBJECTS, lambda row: row["code"], "subjects")
    _unique_keys(
        DEMO_EXAMINATIONS,
        lambda row: (row["name"], row["held_on"]),
        "examinations",
    )
    _unique_keys(
        all_marks,
        lambda row: (row["admission_number"], row["subject_code"], row["examination_name"], row["held_on"]),
        "marks",
    )
    _unique_keys(EXTRA_CONCERNS, lambda row: row["seed_key"], "concerns")
    _unique_keys(
        tuple(extra_attendance()),
        lambda row: (row["admission_number"], row["subject_code"], row["session_date"]),
        "attendance",
    )

    student_numbers = {row["admission_number"] for row in all_students}
    subject_codes = {row["code"] for row in DEMO_SUBJECTS}
    examination_keys = {(row["name"], row["held_on"]) for row in DEMO_EXAMINATIONS}

    for student in all_students:
        if not student["admission_number"].strip():
            raise ValueError("A demo admission number cannot be empty.")
        if not student["full_name"].strip():
            raise ValueError("A demo student name cannot be empty.")
        clean_email(student["email"])

    for resource in DEMO_RESOURCES:
        if resource["subject_code"] not in subject_codes:
            raise ValueError(f"Demo resource uses unknown subject {resource['subject_code']}.")
        if resource["resource_type"] not in RESOURCE_TYPES:
            raise ValueError(f"Demo resource type '{resource['resource_type']}' is not supported.")
        if not resource["url"].startswith("https://"):
            raise ValueError("Demo resources must use an https URL.")
        if not resource["title"].strip() or not resource["topic"].strip():
            raise ValueError("A demo resource needs a title and a topic.")

    for item in DEMO_FEEDBACK:
        if item["admission_number"] not in student_numbers:
            raise ValueError(f"Demo feedback uses unknown student {item['admission_number']}.")
        if item["subject_code"] not in subject_codes:
            raise ValueError(f"Demo feedback uses unknown subject {item['subject_code']}.")
        if item["preferred_format"] not in PREFERRED_FORMATS:
            raise ValueError("Demo feedback uses an unknown learning format.")

    for subject in DEMO_SUBJECTS:
        if not subject["code"].strip() or not subject["name"].strip():
            raise ValueError("A demo subject needs both a code and a name.")

    for examination in DEMO_EXAMINATIONS:
        if examination["exam_type"] not in EXAM_TYPES:
            raise ValueError(
                f"Demo examination type '{examination['exam_type']}' is not supported."
            )
        if not examination["name"].strip():
            raise ValueError("A demo examination name cannot be empty.")

    for item in EXTRA_CONCERNS:
        if item["admission_number"] not in student_numbers:
            raise ValueError(f"Demo concern uses unknown student {item['admission_number']}.")
        if item["subject_code"] not in subject_codes:
            raise ValueError(f"Demo concern uses unknown subject {item['subject_code']}.")
        if item["status"] not in {
            "submitted", "under_review", "resources_recommended", "in_progress", "resolved", "closed",
        }:
            raise ValueError(f"Demo concern status '{item['status']}' is not supported.")
        if item["preferred_format"] not in PREFERRED_FORMATS:
            raise ValueError("Demo concern uses an unknown learning format.")

    for mark in all_marks:
        if mark["admission_number"] not in student_numbers:
            raise ValueError(
                f"Demo mark uses unknown student {mark['admission_number']}."
            )
        if mark["subject_code"] not in subject_codes:
            raise ValueError(f"Demo mark uses unknown subject {mark['subject_code']}.")
        exam_key = (mark["examination_name"], mark["held_on"])
        if exam_key not in examination_keys:
            raise ValueError(
                f"Demo mark uses unknown examination {mark['examination_name']}."
            )
        validate_mark_values(
            mark["marks_obtained"],
            mark["maximum_marks"],
            mark["pass_marks"],
        )


def _insert_if_absent(session: Session, model, values: dict, conflict_columns: list[str]) -> int:
    """Insert a row unless its unique columns are already stored. Returns 1 or 0."""
    statement = (
        pg_insert(model)
        .values(**values)
        .on_conflict_do_nothing(index_elements=conflict_columns)
        .returning(model.id)
    )
    created = session.execute(statement).first()
    return 1 if created is not None else 0


def _rows_by(session: Session, model, key_func) -> dict:
    return {key_func(row): row for row in session.scalars(select(model)).all()}


